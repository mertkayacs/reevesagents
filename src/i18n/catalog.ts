for (const [language, overrides] of Object.entries(phraseOverrides) as Array<[LanguageCode, Record<string, string>]>) {
  Object.assign(phraseCatalogs[language], overrides)
}

export function translate(language: LanguageCode, key: TranslationKey, values: Record<string, string | number> = {}): string {
  const catalog = catalogs[language] ?? catalogs[DEFAULT_LANGUAGE]
  let text = catalog[key] ?? catalogs[DEFAULT_LANGUAGE][key] ?? key
  for (const [name, value] of Object.entries(values)) {
    text = text.replaceAll(`{{${name}}}`, String(value))
  }
  return text
}

export function localeCatalog(language: LanguageCode): Catalog {
  return catalogs[language] ?? catalogs[DEFAULT_LANGUAGE]
}

export function translatePhrase(language: LanguageCode, text: string): string {
  const direct = phraseCatalogs[language]?.[text]
  if (direct) return direct
  const key = phraseKeyByEnglishText.get(text)
  return key ? translate(language, key) : text
}
